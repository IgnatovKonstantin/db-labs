-- Проверка разницы между платежом и суммой поизиций
SELECT 
    o.order_number, 
    p.amount AS payment_amount,
    SUM(ROUND(i.quantity * i.actual_price * (1 - i.discount_percent / 100), 2)) AS items_amount,
    p.amount - SUM(ROUND(i.quantity * i.actual_price * (1 - i.discount_percent / 100), 2)) AS difference
FROM customer_order o 
JOIN payment p ON p.order_id = o.order_id
JOIN order_item i ON i.order_id = o.order_id
GROUP BY o.order_number, p.amount 
ORDER BY o.order_number;